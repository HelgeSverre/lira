    /// Check if a specific opcode appears in the bytecode's code section
    fn find_opcode(bytecode: &[u8], opcode: Opcode) -> bool {
        let code_section = extract_code_section(bytecode);
        code_section.contains(&(opcode as u8))
    }

    /// Count occurrences of a specific opcode in the code section
    fn count_opcode(bytecode: &[u8], opcode: Opcode) -> usize {
        let code_section = extract_code_section(bytecode);
        code_section.iter().filter(|&&b| b == opcode as u8).count()
    }

    /// Extract the code section from bytecode (skipping header and constant pool)
    fn extract_code_section(bytecode: &[u8]) -> &[u8] {
        // Header is 24 bytes (6 * 4-byte u32s)
        // Then we need to skip the constant pool
        let header_size = 24;
        if bytecode.len() < header_size + 4 {
            return &[];
        }

        // Read constant count from header (offset 16)
        let constant_count =
            u32::from_le_bytes([bytecode[16], bytecode[17], bytecode[18], bytecode[19]]) as usize;

        // Skip constants - we need to parse each one to know its size
        let mut offset = header_size;
        for _ in 0..constant_count {
            if offset >= bytecode.len() {
                return &[];
            }
            let const_type = bytecode[offset];
            offset += 1;
            match const_type {
                0x00 => {}           // Null - no additional bytes
                0x01 => offset += 1, // Bool - 1 byte
                0x02 => offset += 8, // Int - 8 bytes (i64)
                0x03 => offset += 8, // Float - 8 bytes (f64)
                0x04 => {
                    // String - 4 bytes length + string bytes
                    if offset + 4 > bytecode.len() {
                        return &[];
                    }
                    let len = u32::from_le_bytes([
                        bytecode[offset],
                        bytecode[offset + 1],
                        bytecode[offset + 2],
                        bytecode[offset + 3],
                    ]) as usize;
                    offset += 4 + len;
                }
                0x05 => offset += 8, // Function - 8 bytes (u64 offset)
                _ => return &[],     // Unknown constant type
            }
        }

        // Read code section length
        if offset + 4 > bytecode.len() {
            return &[];
        }
        let code_len = u32::from_le_bytes([
            bytecode[offset],
            bytecode[offset + 1],
            bytecode[offset + 2],
            bytecode[offset + 3],
        ]) as usize;
        offset += 4;

        // Return the code section
        if offset + code_len <= bytecode.len() {
            &bytecode[offset..offset + code_len]
        } else {
            &[]
        }
    }

    /// Get constants from bytecode
    fn get_int_constants(bytecode: &[u8]) -> Vec<i64> {
        let header_size = 24;
        if bytecode.len() < header_size {
            return vec![];
        }

        let constant_count =
            u32::from_le_bytes([bytecode[16], bytecode[17], bytecode[18], bytecode[19]]) as usize;

        let mut offset = header_size;
        let mut ints = Vec::new();

        for _ in 0..constant_count {
            if offset >= bytecode.len() {
                break;
            }
            let const_type = bytecode[offset];
            offset += 1;
            match const_type {
                0x00 => {}
                0x01 => offset += 1,
                0x02 => {
                    if offset + 8 <= bytecode.len() {
                        let val = i64::from_le_bytes([
                            bytecode[offset],
                            bytecode[offset + 1],
                            bytecode[offset + 2],
                            bytecode[offset + 3],
                            bytecode[offset + 4],
                            bytecode[offset + 5],
                            bytecode[offset + 6],
                            bytecode[offset + 7],
                        ]);
                        ints.push(val);
                    }
                    offset += 8;
                }
                0x03 => offset += 8,
                0x04 => {
                    if offset + 4 > bytecode.len() {
                        break;
                    }
                    let len = u32::from_le_bytes([
                        bytecode[offset],
                        bytecode[offset + 1],
                        bytecode[offset + 2],
                        bytecode[offset + 3],
                    ]) as usize;
                    offset += 4 + len;
                }
                0x05 => offset += 8,
                _ => break,
            }
        }

        ints
    }

    fn get_string_constants(bytecode: &[u8]) -> Vec<String> {
        let header_size = 24;
        if bytecode.len() < header_size {
            return vec![];
        }

        let constant_count =
            u32::from_le_bytes([bytecode[16], bytecode[17], bytecode[18], bytecode[19]]) as usize;

        let mut offset = header_size;
        let mut strings = Vec::new();

        for _ in 0..constant_count {
            if offset >= bytecode.len() {
                break;
            }
            let const_type = bytecode[offset];
            offset += 1;
            match const_type {
                0x00 => {}
                0x01 => offset += 1,
                0x02 => offset += 8,
                0x03 => offset += 8,
                0x04 => {
                    if offset + 4 > bytecode.len() {
                        break;
                    }
                    let len = u32::from_le_bytes([
                        bytecode[offset],
                        bytecode[offset + 1],
                        bytecode[offset + 2],
                        bytecode[offset + 3],
                    ]) as usize;
                    offset += 4;
                    if offset + len <= bytecode.len() {
                        if let Ok(s) = String::from_utf8(bytecode[offset..offset + len].to_vec()) {
                            strings.push(s);
                        }
                    }
                    offset += len;
                }
                0x05 => offset += 8,
                _ => break,
            }
        }

        strings
    }

