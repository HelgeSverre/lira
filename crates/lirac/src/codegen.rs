/// Code generator
pub struct CodeGenerator {
    /// Constant pool
    constants: Vec<Constant>,
    /// Constant lookup for deduplication
    constant_map: HashMap<ConstantKey, u16>,
    /// Generated bytecode
    code: Vec<u8>,
    /// Pending function reference patches: (constant_index, function_name)
    pending_func_patches: Vec<(u16, String)>,
    /// Function table
    functions: Vec<FunctionInfo>,
    /// Current function being compiled
    #[allow(dead_code)]
    current_function: Option<usize>,
    /// Local variable slots per scope
    locals: Vec<HashMap<String, u16>>,
    /// Local variable types per scope (for method dispatch)
    local_types: Vec<HashMap<String, String>>,
    /// Next local slot
    next_local: u16,
    /// Current scope depth (for debug symbols)
    scope_depth: u16,
    /// Loop context for break/continue
    loop_stack: Vec<LoopContext>,
    /// Errors during code generation
    errors: Vec<CodegenError>,
    /// Debug information
    debug_info: DebugInfo,
    /// Struct method table: struct_name -> method_name -> code_offset.
    /// Also holds each class's OWN methods (inherited methods are resolved by
    /// walking `class_parents` at instance-construction time).
    struct_methods: HashMap<String, HashMap<String, usize>>,
    /// Class inheritance edges: class_name -> parent class name (if any). Used to
    /// resolve the full method set (own + inherited, child overrides win) when a
    /// class instance is constructed. Only classes appear here.
    class_parents: HashMap<String, Option<String>>,
    /// Captured variables for current closure (name -> capture index)
    captures: Vec<String>,
    /// Function default parameter values: fn_name -> [(param_index, default_expr)]
    function_defaults: FunctionDefaults,
    /// Function parameter names (in declaration order): fn_name -> [param_name, ...].
    /// Used to reorder named arguments at call sites into positional order.
    function_param_names: HashMap<String, Vec<String>>,
    /// Module-level constants: name -> constant pool index
    module_consts: HashMap<String, u16>,
    /// Impl methods for all types: type_name -> {method_name -> mangled_function_name}
    impl_methods: HashMap<String, HashMap<String, String>>,
    /// Declared return types of impl methods: type_name -> {method_name -> return type display}.
    /// Used so chained method calls (e.g. `self.sort().reverse()`) can recover the
    /// receiver type of the outer call and dispatch via the typed-impl path.
    impl_method_returns: HashMap<String, HashMap<String, String>>,
    /// Semantic tables produced by the type checker (authoritative expression types).
    sema: SemanticTables,
}

/// Key for constant deduplication
#[derive(Hash, Eq, PartialEq)]
enum ConstantKey {
    Int(i64),
    Float(u64), // bits
    String(String),
    Bool(bool),
    Function(usize),
}

/// Function information
struct FunctionInfo {
    name: String,
    code_offset: usize,
    param_count: u8,
    local_count: u16,
}

/// Function parameter defaults: fn_name -> vec of (param_index, default_expr)
type FunctionDefaults = HashMap<String, Vec<(usize, Expression)>>;

/// Loop context for break/continue
struct LoopContext {
    #[allow(dead_code)]
    start_offset: usize,
    continue_target: Option<usize>, // None = use patches; Some(x) = direct jump to x
    break_patches: Vec<usize>,
    continue_patches: Vec<usize>,
}

